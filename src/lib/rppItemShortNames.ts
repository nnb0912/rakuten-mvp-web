export function shortRppItemName(itemCode: string, fallback = "") {
  const known = RPP_ITEM_SHORT_NAMES[itemCode.trim().toLowerCase()]?.trim();
  if (known) return known;
  const normalized = fallback.replace(/\s+/g, " ").trim();
  if (!normalized) return itemCode || "商品名未取得";
  const chars = Array.from(normalized);
  return chars.length > 24 ? `${chars.slice(0, 24).join("")}…` : normalized;
}
